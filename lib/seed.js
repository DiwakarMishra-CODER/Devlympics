/**
 * Helper to compute an ISO timestamp relative to now within the last 7 days.
 *
 * @param {number} daysAgo - Float or integer days in the past
 * @param {number} hoursAgo - Additional hours
 * @returns {string} ISO timestamp
 */
function getPastDate(daysAgo, hoursAgo = 0) {
  const ms = Date.now() - (daysAgo * 24 + hoursAgo) * 60 * 60 * 1000;
  return new Date(ms).toISOString();
}

/**
 * Computes follow-up date 3 days after creation.
 *
 * @param {string} createdAtIso
 * @returns {string} ISO timestamp
 */
function getFollowUpDate(createdAtIso) {
  const ms = new Date(createdAtIso).getTime() + 3 * 24 * 60 * 60 * 1000;
  return new Date(ms).toISOString();
}

